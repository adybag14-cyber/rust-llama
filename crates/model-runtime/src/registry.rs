/// Recheck the frozen registries against a separately supplied reference tree.
/// This parser intentionally targets the frozen archive's simple enum, map and
/// switch syntax; it is not a general C++ or Python parser. Runtime builds do
/// not read or depend on the reference tree.
pub fn audit_snapshot(
    root: impl AsRef<std::path::Path>,
) -> std::result::Result<RegistryAudit, String> {
    use std::{collections::BTreeSet, fs};
    let root = root.as_ref();
    let read = |name: &str| fs::read_to_string(root.join(name)).map_err(|e| format!("{name}: {e}"));
    let header = read("src/llama-arch.h")?;
    let enum_body = header
        .split_once("enum llm_arch {")
        .and_then(|(_, v)| v.split_once("};"))
        .ok_or("architecture enum markers missing")?
        .0;
    let symbols: Vec<&str> = enum_body
        .split(',')
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .collect();
    if symbols.len() != ARCHITECTURES.len() {
        return Err(format!(
            "expected 173 architecture slots, got {}",
            symbols.len()
        ));
    }
    for (expected, actual) in ARCHITECTURES.iter().zip(symbols) {
        if expected.cpp_enum != actual {
            return Err(format!(
                "architecture slot {}: expected {}, got {actual}",
                expected.id, expected.cpp_enum
            ));
        }
    }
    let names = read("src/llama-arch.cpp")?;
    let names = names
        .split_once("LLM_ARCH_NAMES = {")
        .and_then(|(_, v)| v.split_once("};"))
        .ok_or("architecture names markers missing")?
        .0;
    let mut observed = std::collections::BTreeMap::new();
    for line in names.lines() {
        let line = line.trim();
        if let Some(line) = line.strip_prefix('{') {
            let (symbol, rest) = line.split_once(',').ok_or("malformed name entry")?;
            let name = rest.split('"').nth(1).ok_or("missing name string")?;
            if observed.insert(symbol.trim(), name).is_some() {
                return Err("duplicate architecture name entry".into());
            }
        }
    }
    if observed.len() != ARCHITECTURES.len() {
        return Err("architecture name count differs".into());
    }
    for expected in &ARCHITECTURES {
        if observed.get(expected.cpp_enum).copied() != Some(expected.name) {
            return Err(format!("canonical name differs for {}", expected.cpp_enum));
        }
    }
    let dispatch = read("src/llama-model.cpp")?;
    let dispatch = dispatch
        .split_once("static llama_model * llama_model_mapping")
        .and_then(|(_, v)| v.split_once("llama_model * llama_model_create"))
        .ok_or("model dispatch markers missing")?
        .0;
    let mut factories = std::collections::BTreeMap::new();
    let mut current = None;
    for line in dispatch.lines().map(str::trim) {
        if let Some(symbol) = line.strip_prefix("case ").and_then(|v| v.strip_suffix(':')) {
            current = Some(symbol);
        }
        if let Some(class) = line
            .strip_prefix("return new ")
            .and_then(|v| v.strip_suffix("(params);"))
        {
            let symbol = current.take().ok_or("factory without preceding case")?;
            factories.insert(symbol, class);
        }
    }
    for expected in &ARCHITECTURES {
        if factories.get(expected.cpp_enum).copied() != expected.source_factory {
            return Err(format!("source factory differs for {}", expected.cpp_enum));
        }
    }
    if factories.len() != 171 {
        return Err(format!("source factory count differs: {}", factories.len()));
    }
    let mut files = BTreeSet::new();
    for entry in fs::read_dir(root.join("src/models")).map_err(|e| e.to_string())? {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.extension().is_some_and(|e| e == "cpp") {
            files.insert(format!(
                "src/models/{}",
                path.file_name()
                    .ok_or("missing filename")?
                    .to_string_lossy()
            ));
        }
    }
    let expected: BTreeSet<String> = MODEL_SOURCE_FILES.iter().map(|s| s.to_string()).collect();
    if files != expected {
        return Err(format!(
            "model source files differ: missing {:?}, extra {:?}",
            expected.difference(&files),
            files.difference(&expected)
        ));
    }
    let mut registrations = Vec::new();
    for entry in fs::read_dir(root.join("conversion")).map_err(|e| e.to_string())? {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.extension().is_none_or(|e| e != "py") {
            continue;
        }
        let source = fs::read_to_string(&path).map_err(|e| e.to_string())?;
        let filename = format!(
            "conversion/{}",
            path.file_name()
                .ok_or("missing filename")?
                .to_string_lossy()
        );
        let mut decorator = String::new();
        let mut reading = false;
        for line in source.lines() {
            let line = line.trim();
            if line.starts_with("@ModelBase.register(") {
                reading = true;
                decorator.clear();
            }
            if !reading {
                continue;
            }
            decorator.push_str(line);
            if !line.contains(')') {
                continue;
            }
            reading = false;
            // Actual decorators contain literal single/double quoted aliases.
            let mut chars = decorator.chars();
            while let Some(ch) = chars.next() {
                if ch == '\'' || ch == '"' {
                    let value: String = chars.by_ref().take_while(|&c| c != ch).collect();
                    registrations.push((filename.clone(), value));
                }
            }
        }
    }
    registrations.sort();
    let mut expected: Vec<_> = CONVERSION_ALIASES
        .iter()
        .map(|a| (a.source.to_string(), a.name.to_string()))
        .collect();
    expected.sort();
    if registrations != expected {
        return Err(format!(
            "conversion registrations differ (expected {}, observed {})",
            expected.len(),
            registrations.len()
        ));
    }
    Ok(RegistryAudit {
        architecture_slots: ARCHITECTURES.len(),
        named_architectures: ARCHITECTURES.len() - 1,
        source_factory_cases: factories.len(),
        model_source_files: files.len(),
        text_conversion_registrations: CONVERSION_ALIASES
            .iter()
            .filter(|a| a.text_architecture_id.is_some())
            .count(),
        projector_conversion_registrations: CONVERSION_ALIASES
            .iter()
            .filter(|a| a.text_architecture_id.is_none())
            .count(),
    })
}

